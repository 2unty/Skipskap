CREATE SCHEMA IF NOT EXISTS Scanned;

CREATE TABLE IF NOT EXISTS Scanned.APS(
    ID INT AUTO_INCREMENT PRIMARY KEY,
    SSID VARCHAR(20) NOT NULL,
    BSSID VARCHAR(50),
    VENDOR VARCHAR(20),
    HOSTS INT NOT NULL,
    COUNT INT NOT NULL,
    RSSI INT NOT NULL,
    TIMESTAMP BIGINT NOT NULL,
    FIRSTSIG BIGINT NOT NULL,
    COMMENT VARCHAR(20)
);

CREATE TABLE IF NOT EXISTS Scanned.HOSTS(
    ID INT AUTO_INCREMENT PRIMARY KEY,
    MAC VARCHAR(20) NOT NULL,
    VENDOR VARCHAR(50),
    RSSI INT NOT NULL,
    COUNT INT NOT NULL,
    ALIAS VARCHAR(20),
    TIMESTAMP BIGINT NOT NULL,
    FIRSTSIG BIGINT NOT NULL,
    COMMENT VARCHAR(20)
);

CREATE TABLE IF NOT EXISTS Scanned.BTS(
    ID INT AUTO_INCREMENT PRIMARY KEY,
    MAC VARCHAR(20) NOT NULL,
    COMPANY VARCHAR(50),
    LOCALNAME VARCHAR(50),
    VENDOR VARCHAR(50),
    RSSI INT NOT NULL,
    TIMESTAMP BIGINT NOT NULL,
    FIRSTSIG BIGINT NOT NULL,
    COMMENT VARCHAR(20)
);

CREATE TABLE IF NOT EXISTS Scanned.LINKS(
    ID INT AUTO_INCREMENT PRIMARY KEY,
    HID INT NOT NULL,
    APID INT NOT NULL,
    COUNT INT NOT NULL,
    TIMESTAMP BIGINT NOT NULL,
    FOREIGN KEY (HID) REFERENCES HOSTS(ID),
    FOREIGN KEY (APID) REFERENCES APS(ID)
);
